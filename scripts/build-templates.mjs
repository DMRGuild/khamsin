// Precompiles the eta templates into src/templates.gen.mjs. The Workers
// runtime disallows code generation from strings (new Function), so eta
// cannot compile at request time — this script does it at build time and
// emits the compiled template functions as plain source. Run automatically
// by `npm run dev` / `npm run deploy`; re-run after editing any .eta file.
//
// IMPORTANT: the Eta options here must match the runtime instance in
// src/templates.ts (autoEscape: true, default varName/escapeFunction) —
// escaping behavior is baked in at compile time.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Eta } from "eta";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const eta = new Eta({ autoEscape: true });

const TEMPLATES = {
  "@layout": "views/layout.eta",
  "@index": "views/index.eta",
  "@about": "views/about.eta",
  "@record": "views/record.eta",
  "@settings": "views/settings.eta",
  "@admin": "views/admin.eta",
  "@error": "views/error.eta",
  "@denied": "views/denied.eta",
  "@partials/authbar": "views/partials/authbar.eta",
  "@partials/sidebar": "views/partials/sidebar.eta",
  "@partials/tipjar": "views/partials/tipjar.eta",
  "@partials/gentou": "views/partials/gentou.eta",
  "@partials/lightning-core": "views/partials/lightning-core.eta",
};

let out =
  "// GENERATED by scripts/build-templates.mjs — do not edit by hand.\n" +
  "// Compiled eta template functions (the Workers runtime cannot compile\n" +
  "// templates itself: code generation from strings is disallowed).\n" +
  "export const templates = {\n";

for (const [name, path] of Object.entries(TEMPLATES)) {
  const src = readFileSync(join(root, path), "utf8");
  let fn;
  try {
    fn = eta.compile(src);
  } catch (err) {
    console.error(`failed to compile ${path}:`, err.message);
    process.exit(1);
  }
  out += `  ${JSON.stringify(name)}: ${fn.toString()},\n`;
}
out += "};\n";

writeFileSync(join(root, "src/templates.gen.mjs"), out);
console.log(
  `wrote src/templates.gen.mjs (${Object.keys(TEMPLATES).length} templates)`,
);
